def infer_pattern(point: str) -> tuple[str, str, str, str, str] | None:
    key = normalize_pattern(point)
    for pattern, meaning, rule, jp, zh, jlpt in _SUFFIX_RULES:
        if re.search(pattern, key):
            return meaning, rule, jp, zh, jlpt
    return None


def fill_raw_row(row: GrammarRawRow) -> GrammarRawRow:
    if row.parse_status == "complete" and row.meaning_zh and row.example_japanese:
        return row

    kb = lookup_grammar(row.grammar_point) or infer_pattern(row.grammar_point)
    if not kb:
        return row

    meaning, rule, jp, zh, _jlpt = kb
    return GrammarRawRow(
        entry_id=row.entry_id,
        grammar_point=row.grammar_point,
        semantic_concept=row.meaning_zh or meaning,
        connection_rule=row.connection_rule or rule,
        meaning_zh=row.meaning_zh or meaning,
        example_japanese=row.example_japanese or jp,
        example_chinese=row.example_chinese or zh,
        raw_notes=row.raw_notes,
        source_page=row.source_page,
        source_line=row.source_line,
        parse_status="partial" if row.parse_status == "index_only" else row.parse_status,
    )


def main() -> None:
    raw_path = EXTRACTED / "grammar_raw.csv"
    rows = read_csv(raw_path, GrammarRawRow)
    before = sum(1 for r in rows if not r.meaning_zh or not r.example_japanese)

    filled = [fill_raw_row(r) for r in rows]
    write_csv(raw_path, filled)

    curated = [enrich_grammar_row(r) for r in filled]
    curated_path = CURATED / "grammar.csv"
    write_csv(curated_path, curated)

    after = sum(1 for r in filled if not r.meaning_zh or not r.example_japanese)
    kb_hits = sum(1 for r in rows if lookup_grammar(r.grammar_point) or infer_pattern(r.grammar_point))
    print(f"[Agent 3] KB entries: {len(GRAMMAR_KB)}")
    print(f"[Agent 3] Patterns matchable: {kb_hits}/{len(rows)}")
    print(f"[Agent 3] Incomplete before={before} after={after}")
    print(f"  → updated {raw_path}")
    print(f"  → updated {curated_path}")


if __name__ == "__main__":
    main()
